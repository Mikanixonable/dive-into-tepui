// 1 文字を RGB 画素列へ描く。戻り値は進んだ幅 [px]。
function drawChar(rgb, width, height, x0, y0, ch, color) {
  const glyph = GLYPHS[ch.toUpperCase()] ?? GLYPHS[' '];
  for (let y = 0; y < 7; y++) {
    for (let x = 0; x < 5; x++) {
      if (glyph[y][x] !== '1') continue;
      const px = x0 + x;
      const py = y0 + y;
      if (px < 0 || px >= width || py < 0 || py >= height) continue;
      const i = (py * width + px) * 3;
      rgb[i] = color[0];
      rgb[i + 1] = color[1];
      rgb[i + 2] = color[2];
    }
  }
  return 6;
}

// 文字列を描く。
function drawText(rgb, width, height, x0, y0, text, color) {
  let x = x0;
  for (const ch of text) x += drawChar(rgb, width, height, x, y0, ch, color);
}

const COLS = 6;
const THUMB = 128;
const PAD = 4;
const TITLE_H = 12;
const LABEL_H = 10;

// 見出し title と {label, rgb:128*128*3} の並びから接触シートの PNG バイト列を組む。
export function buildContactSheet(title, thumbs) {
  const cols = Math.min(COLS, Math.max(1, thumbs.length));
  const rows = Math.ceil(Math.max(1, thumbs.length) / cols);
  const width = cols * (THUMB + PAD) + PAD;
  const height = TITLE_H + rows * (THUMB + LABEL_H + PAD) + PAD;
  const rgb = new Uint8Array(width * height * 3).fill(24);
  drawText(rgb, width, height, PAD, 3, title, [255, 255, 255]);
  for (let i = 0; i < thumbs.length; i++) {
    const cx = PAD + (i % cols) * (THUMB + PAD);
    const cy = TITLE_H + Math.floor(i / cols) * (THUMB + LABEL_H + PAD);
    const thumb = thumbs[i].rgb;
    for (let y = 0; y < THUMB; y++) {
      for (let x = 0; x < THUMB; x++) {
        const from = (y * THUMB + x) * 3;
        const to = ((cy + y) * width + cx + x) * 3;
        rgb[to] = thumb[from];
        rgb[to + 1] = thumb[from + 1];
        rgb[to + 2] = thumb[from + 2];
      }
    }
    drawText(rgb, width, height, cx, cy + THUMB + 2, thumbs[i].label, [200, 220, 255]);
  }
  return encodeRgbPng(width, height, rgb);
}
