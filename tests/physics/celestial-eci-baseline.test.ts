const J2000_JD = 2451545;

// 暦パック経路を通すためだけの供給源。位置は時刻の一次式で、物理的な意味は無い — 検査したいのは
// 「どの天体がどちらの経路を通り、原点がどちらから引かれるか」の配線だけ。**月と木星をわざと
// 外してある**: 月は「収録済みの親 + 解析の相対」、木星は「両端とも解析」へ落ちる経路を通り、
// 地球(ECI 原点)と火星はパック経路を通る。
const SOURCE: AbsoluteEphemeris = {
  validStartJdTdb: J2000_JD - 500,
  validEndJdTdb: J2000_JD + 500,
  hasBody: (id) => id === 'sun' || id === 'earth' || id === 'mars',
  barycentricStateOf: (id, jd) => {
    const d = jd - J2000_JD;
    if (id === 'sun') return { r: v3(1e6 * d, 2e6, -3e6), v: v3(1e6 / 86400, 0, 0) };
    if (id === 'earth') {
      return { r: v3(1.5e11 + 1e6 * d, 2e6 + 3e8 * d, -3e6), v: v3(1e6 / 86400, 3e8 / 86400, 0) };
    }
    return { r: v3(-2.2e11 + 1e6 * d, 2e6 - 1e8 * d, 4e10), v: v3(1e6 / 86400, -1e8 / 86400, 0) };
  },
};

