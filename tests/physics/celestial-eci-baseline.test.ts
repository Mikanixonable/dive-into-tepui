// 太陽の地心位置と、重心補正なしの純ケプラー地球から見た太陽位置との差(= 重心補正そのもの)。
// TIMES の先頭2つで測る。
const BARY_OFFSET: Baseline = [
    [4097911.1021728516, -727928.605142355, 1350187.2564821243],
    [4326429.3408203125, -177394.6080470085, 367568.25833797455],
];

export function register(): void {
  const analytic = solarSystemParts();
  const packed = solarSystemParts({}, EPOCH_T_OFFSET, SOURCE, J2000_JD);

  const assertBaseline = (
    parts: ReturnType<typeof solarSystemParts>, id: string, rows: Baseline,
  ): void => {
    TIMES.forEach((t, i) => {
      const s = motionOf(parts, id).stateAt(t);
      assert.deepEqual([s.r.x, s.r.y, s.r.z, s.v.x, s.v.y, s.v.z], rows[i], `${id} t=${t}`);
    });
  };

  for (const [id, rows] of Object.entries(ANALYTIC)) {
    test(`eci-baseline: 解析暦の ${id} の ECI 位置・速度が固定値と一致する`, () => {
      assertBaseline(analytic, id, rows);
    });
  }

  for (const [id, rows] of Object.entries(PACKED)) {
    test(`eci-baseline: 暦パック構成の ${id} の ECI 位置・速度が固定値と一致する`, () => {
      assertBaseline(packed, id, rows);
    });
  }

  test('eci-baseline: 重心補正(太陽の地心位置と純ケプラー地球の差)が固定値と一致する', () => {
    const orbit = keplerOrbitAtEpoch(EARTH.orbit, 0, EPOCH_T_OFFSET);
    TIMES.slice(0, BARY_OFFSET.length).forEach((t, i) => {
      const d = sub(motionOf(analytic, 'sun').stateAt(t).r, scale(keplerOrbitState(orbit, t).r, -1));
      assert.deepEqual([d.x, d.y, d.z], BARY_OFFSET[i], `bary t=${t}`);
    });
  });
}
