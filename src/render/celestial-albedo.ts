// 実写テクスチャを持たない天体の拡散アルベド。**天体は明るさそのものを持たない** — 見た目の
// 明るさは、その天体がいまいる場所で受けている放射照度とこの反射率の積として毎フレーム決まる。
//
// **入れるのはボンドアルベド $A_B$(全方向・全波長へ返す割合)であって幾何アルベド $p$ では
// ない。** ランバート球の $A_B$ は拡散アルベド $\rho$ そのもので、同じ球の $p$ は $\tfrac23\rho$
// にしかならない。$p$ をそのまま入れると天体が受けた光より多く返し、Phase 8 で天体を光源に
// したときのエネルギーが $1/q$ 倍(天体によっては 2〜3 倍)過大になる。
//
// **値の出どころ。** 公表されたボンドアルベドがある天体はそれを直に入れる。幾何アルベドしか
// 公表されていない天体は、位相積分 $q$ を掛けて $A_B = p q$ へ直してから入れる。$q$ は H–G 系
// (Bowell et al. 1989)の $q = 0.290 + 0.684\,G$ を分類ごとの $G$ で評価した:
//
// - $q = 0.393$($G = 0.15$、IAU 既定値) — C/D 型小惑星・彗星核・暗い捕獲衛星
// - $q = 0.461$($G = 0.25$) — S/M 型小惑星・岩石質の衛星・中程度の TNO
// - $q = 0.564$($G = 0.40$) — 明るい氷天体(エンケラドゥスの公表 $A_B/p = 0.81/1.375$ と一致する)
//
// 個別の一次文献までは当たっておらず、幾何アルベドは各天体の一般的な公表値を採った。**個別の
// 公表値が見つからず分類の代表値を置いたものは、その旨をコメントへ明記してある。**
//
// **色相は輝度と別に持つ。** 各値は「その天体の色みを保ったまま、Rec.709 輝度が $A_B$ に
// 一致するよう倍率を合わせた線形 RGB」で、輝度が物理量、色みは見た目の値。
//
// **衝効果(opposition surge)はモデル化していない。** 満月に近い構図で写真より暗く写るのは
// その正しい帰結で、アルベドを盛って埋めてはならない(埋めるなら再帰反射項を足す)。

// 線形 RGB の拡散アルベド。各成分は 0..1。
export type Albedo = readonly [number, number, number];

